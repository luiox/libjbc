/// @brief 操作数布局：唯一决定指令长度与编码方式。
enum class Shape : ca::u8 {
    None = 0,      ///< 无操作数（1 字节）
    Imm1 = 1,      ///< i8 立即数（bipush）
    Imm2 = 2,      ///< i16 立即数（sipush）
    Local1 = 3,    ///< u8 局部变量索引（iload/astore/ret…）
    Iinc1 = 4,     ///< u8 局部变量索引 + i8 常量（iinc）
    CP1 = 5,       ///< u8 CP 索引（ldc）
    CP2 = 6,       ///< u16 CP 索引
    CP2Count = 7,  ///< u16 CP + u8 count + u8 zero（invokeinterface）
    CP2Zero2 = 8,  ///< u16 CP + u8 0 + u8 0（invokedynamic）
    CP2Dims = 9,   ///< u16 CP + u8 维数（multianewarray）
    Atype1 = 10,   ///< u8 数组元素类型（newarray）
    Branch2 = 11,  ///< i16 分支偏移
    Branch4 = 12,  ///< i32 分支偏移（goto_w/jsr_w）
    TableSwitch = 13,
    LookupSwitch = 14,
};

/// @brief 指令的操作数布局（wide 前缀展开后的实际形状由解码器结合标志处理）。
Shape shapeOf(Op op) noexcept;

/// @brief 助记符（诊断输出用）。
const char* mnemonicOf(Op op) noexcept;

/// @brief 该 Op 是否为 wide 前缀可修饰的指令（局部变量访问 + iinc）。
bool isWideLocalOp(Op op) noexcept;

